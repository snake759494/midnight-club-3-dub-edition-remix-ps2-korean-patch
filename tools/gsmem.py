def _ct32_word_addr():
    """(y,x) in 64x32 -> 페이지 내 워드 번호"""
    a = np.zeros((32, 64), np.int64)
    for y in range(32):
        for x in range(64):
            a[y, x] = BT32[y // 8][x // 8] * 64 + CT32[y % 8][x % 8]
    return a

def _t4_nibble_addr():
    """(y,x) in 128x128 -> 페이지 내 니블 번호"""
    a = np.zeros((128, 128), np.int64)
    for y in range(128):
        for x in range(128):
            a[y, x] = BT4[y // 16][x // 32] * 512 + CT4[y % 16][x % 32]
    return a

A32 = _ct32_word_addr()
A4 = _t4_nibble_addr()


def decode_t4_from_ct32(data):
    """8192 바이트(PSMCT32 64x32 선형으로 업로드된 데이터) -> PSMT4 128x128 인덱스"""
    words = np.frombuffer(data, '<u4').reshape(32, 64)
    mem = np.zeros(2048, '<u4'); mem[A32.reshape(-1)] = words.reshape(-1)
    nib = np.stack([mem.view(np.uint8) & 15, mem.view(np.uint8) >> 4], 1).reshape(-1)
    return nib[A4]


def encode_t4_to_ct32(idx):
    """PSMT4 128x128 인덱스 -> PSMCT32 64x32 선형 업로드 데이터(8192 바이트)"""
    nib = np.zeros(16384, np.uint8); nib[A4.reshape(-1)] = idx.reshape(-1).astype(np.uint8) & 15
    mem = (nib[0::2] | (nib[1::2] << 4)).astype(np.uint8).view('<u4')
    return mem[A32.reshape(-1)].astype('<u4').tobytes()
